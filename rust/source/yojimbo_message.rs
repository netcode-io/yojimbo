/**
    A reference counted object that can be serialized to a bitstream.

    Messages are objects that are sent between client and server across the connection. They are carried inside the ConnectionPacket generated by the Connection class. Messages can be sent reliable-ordered, or unreliable-unordered, depending on the configuration of the channel they are sent over.

    To use messages, create your own set of message classes by inheriting from this class (or from BlockMessage, if you want to attach data blocks to your message), then setup an enum of all your message types and derive a message factory class to create your message instances by type.

    There are macros to help make defining your message factory painless:

        YOJIMBO_MESSAGE_FACTORY_START
        YOJIMBO_DECLARE_MESSAGE_TYPE
        YOJIMBO_MESSAGE_FACTORY_FINISH

    Once you have a message factory, register it with your declared inside your client and server classes using:

        YOJIMBO_MESSAGE_FACTORY

    which overrides the Client::CreateMessageFactory and Server::CreateMessageFactory methods so the client and server classes use your message factory type.

    See shared.h for an example showing you how to do this, and the functional tests inside test.cpp for examples showing how to send and receive messages.

    @see BlockMessage
    @see MessageFactory
    @see Connection
 */

// port: the class's data members live in MessageBase, which every message struct embeds as `base`; the virtual
// methods are the Message trait (README, "Classes with virtual methods"). A user message is
//
//     #[derive(Default)]
//     pub struct TestMessage { pub base: MessageBase, pub sequence: u16 }
//     impl TestMessage { pub fn Serialize<S: Stream>( &mut self, stream: &mut S ) -> bool { serialize_bits!( stream, self.sequence, 16 ); true } }
//     impl Serializable for TestMessage { YOJIMBO_VIRTUAL_SERIALIZE_FUNCTIONS!(); }
//     YOJIMBO_MESSAGE!( TestMessage );
//
// and a block message embeds `pub base: BlockMessage` instead and uses YOJIMBO_BLOCK_MESSAGE!( TestBlockMessage ).
// The message factory macros create messages with Default::default(), the C++ default constructor.

pub struct MessageBase
{
    m_refCount: i32,                            // Number of references on this message object. Starts at 1. Message is destroyed when it reaches 0.
    m_id: u16,                                  // The message id. For messages sent over reliable-ordered channels, this starts at 0 and increases with each message sent. For unreliable-unordered channels this is set to the sequence number of the packet the message was included in.
    m_type: u16,                                // The message type. Corresponds to the type integer used when the message was created though the message factory.
    m_blockMessage: bool,                       // 1 if this is a block message. 0 otherwise. If 1 then you can cast the Message* to BlockMessage*. Lightweight RTTI.
    // port: the bitfields m_id : 16, m_type : 15 and m_blockMessage : 1 are plain fields; SetType keeps 15 bits
}

impl MessageBase
{
    /**
        Message constructor.
        Don't call this directly, use a message factory instead.
        @param blockMessage 1 if this is a block message, 0 otherwise.
        @see MessageFactory::Create
     */

    pub fn new( blockMessage: i32 ) -> MessageBase
    {
        MessageBase { m_refCount: 1, m_id: 0, m_type: 0, m_blockMessage: blockMessage != 0 }
    }
}

// port: Message( int blockMessage = 0 ), the default argument
impl Default for MessageBase
{
    fn default() -> MessageBase
    {
        MessageBase::new( 0 )
    }
}

// port: the C++ destructor `virtual ~Message() { yojimbo_assert( m_refCount == 0 ); }` is not ported as a Drop: Rust
// drops a message value that never reached the allocator (YOJIMBO_NEW! failing, a value built on the stack), which C++
// forbids with a protected destructor. Every allocated message is deleted by MessageFactory::ReleaseMessage, at a
// reference count of 0.

pub trait Message: Serializable
{
    // port: accessors for the embedded data members (README, "Classes with virtual methods")

    fn base( &self ) -> &MessageBase;

    fn base_mut( &mut self ) -> &mut MessageBase;

    // port addition: the downcast C++ does with a cast after IsBlockMessage(). Block messages return Some.

    fn AsBlockMessage( &mut self ) -> Option<&mut BlockMessage> { None }

    /**
        Set the message id.
        When messages are sent over a reliable-ordered channel, the message id starts at 0 and increases with each message sent over that channel.
        When messages are sent over an unreliable-unordered channel, the message id is set to the sequence number of the packet it was delivered in.
        @param id The message id.
     */

    fn SetId( &mut self, id: u16 ) { self.base_mut().m_id = id; }

    /**
        Get the message id.
        @returns The message id.
     */

    fn GetId( &self ) -> i32 { self.base().m_id as i32 }

    /**
        Get the message type.
        This corresponds to the type enum value used to create the message in the message factory.
        @returns The message type.
        @see MessageFactory.
     */

    fn GetType( &self ) -> i32 { self.base().m_type as i32 }

    /**
        Get the reference count on the message.
        Messages start with a reference count of 1 when they are created. This is decreased when they are released.
        When the reference count reaches 0, the message is destroyed.
        @returns The reference count on the message.
     */

    fn GetRefCount( &self ) -> i32 { self.base().m_refCount }

    /**
        Is this a block message?
        Block messages are of type BlockMessage and can have a data block attached to the message.
        @returns True if this is a block message, false otherwise.
        @see BlockMessage.
     */

    fn IsBlockMessage( &self ) -> bool { self.base().m_blockMessage }

    // port: the three pure virtual SerializeInternal overloads come from the Serializable supertrait. Don't implement
    // them by hand: use YOJIMBO_VIRTUAL_SERIALIZE_FUNCTIONS!() to redirect them to a generic Serialize method.

    // port: SetType, Acquire and Release are protected (friend MessageFactory) upstream; trait methods are public

    /**
        Set the message type.
        Called by the message factory after it creates a message.
        @param type The message type.
     */

    fn SetType( &mut self, r#type: i32 ) { self.base_mut().m_type = ( r#type as u16 ) & 0x7FFF; }

    /**
        Add a reference to the message.
        This is called when a message is included in a packet and added to the receive queue.
        This way we don't have to pass messages by value (more efficient) and messages get cleaned up when they are delivered and no packets refer to them.
     */

    fn Acquire( &mut self ) { yojimbo_assert!( self.base().m_refCount > 0 ); self.base_mut().m_refCount += 1; }

    /**
        Remove a reference from the message.
        Message are deleted when the number of references reach zero. Messages have reference count of 1 after creation.
     */

    fn Release( &mut self ) { yojimbo_assert!( self.base().m_refCount > 0 ); self.base_mut().m_refCount -= 1; }
}

/**
    Implement Message for a struct that embeds `base: MessageBase`.
    The struct also implements Serializable, usually with YOJIMBO_VIRTUAL_SERIALIZE_FUNCTIONS!().
 */

// port: stands in for `class X : public Message`
#[macro_export]
macro_rules! YOJIMBO_MESSAGE {
    ( $message_class:ty ) => {
        impl $crate::Message for $message_class
        {
            fn base( &self ) -> &$crate::MessageBase { &self.base }
            fn base_mut( &mut self ) -> &mut $crate::MessageBase { &mut self.base }
        }
    };
}

/**
    Implement Message for a struct that embeds `base: BlockMessage`, so AsBlockMessage() returns the embedded block message.
    The struct also implements Serializable, usually with YOJIMBO_VIRTUAL_SERIALIZE_FUNCTIONS!().
 */

// port: stands in for `class X : public BlockMessage`
#[macro_export]
macro_rules! YOJIMBO_BLOCK_MESSAGE {
    ( $message_class:ty ) => {
        impl $crate::Message for $message_class
        {
            fn base( &self ) -> &$crate::MessageBase { &self.base.base }
            fn base_mut( &mut self ) -> &mut $crate::MessageBase { &mut self.base.base }
            fn AsBlockMessage( &mut self ) -> Option<&mut $crate::BlockMessage> { Some( &mut self.base ) }
        }
    };
}

/**
    Cast a message to its concrete type, as C++ does with `(TestMessage*) message`.
    The message must be a T: check GetType() first, as upstream does. Debug builds assert that the sizes match.
 */

// port addition: the C++ downcast. T is the struct the factory created for this message type.
pub unsafe fn message_cast<'a, T: Message>( message: *mut dyn Message ) -> &'a mut T
{
    yojimbo_assert!( !message.is_null() );
    yojimbo_assert!( std::mem::size_of_val( &*message ) == std::mem::size_of::<T>() );
    &mut *( message as *mut T )
}

/**
    A message which can have a block of data attached to it.
    @see ChannelConfig
 */

// port: a struct that derived block messages embed as `base` (README, "Classes with virtual methods"); it is also a
// message in its own right, as upstream
pub struct BlockMessage
{
    pub base: MessageBase,
    m_allocator: *mut dyn Allocator,            // Allocator for the block attached to the message. NULL if no block is attached.
    m_blockData: *mut u8,                       // The block data. NULL if no block is attached.
    m_blockSize: i32,                           // The block size (bytes). 0 if no block is attached.
}

impl BlockMessage
{
    /**
        Block message constructor.
        Don't call this directly, use a message factory instead.
        @see MessageFactory::CreateMessage
     */

    pub fn new() -> BlockMessage
    {
        BlockMessage { base: MessageBase::new( 1 ), m_allocator: null_allocator(), m_blockData: std::ptr::null_mut(), m_blockSize: 0 }
    }

    /**
        Attach a block to this message.
        You can only attach one block. This method will assert if a block is already attached.
        @see Client::AttachBlockToMessage
        @see Server::AttachBlockToMessage
     */

    pub fn AttachBlock( &mut self, allocator: *mut dyn Allocator, blockData: *mut u8, blockSize: i32 )
    {
        yojimbo_assert!( !blockData.is_null() );
        yojimbo_assert!( blockSize > 0 );
        yojimbo_assert!( self.m_blockData.is_null() );

        self.m_allocator = allocator;
        self.m_blockData = blockData;
        self.m_blockSize = blockSize;
    }

    /**
        Detach the block from this message.
        By doing this you are responsible for copying the block pointer and allocator and making sure the block is freed.
        This could be used for example, if you wanted to copy off the block and store it somewhere, without the cost of copying it.
        @see Client::DetachBlockFromMessage
        @see Server::DetachBlockFromMessage
     */

    pub fn DetachBlock( &mut self )
    {
        self.m_allocator = null_allocator();
        self.m_blockData = std::ptr::null_mut();
        self.m_blockSize = 0;
    }

    /**
        Get the allocator used to allocate the block.
        @returns The allocator for the block. NULL if no block is attached to this message.
     */

    pub fn GetAllocator( &self ) -> *mut dyn Allocator
    {
        self.m_allocator
    }

    /**
        Get the block data pointer.
        @returns The block data pointer. NULL if no block is attached.
     */

    // port: one method stands for the const and non-const overloads
    pub fn GetBlockData( &self ) -> *mut u8
    {
        self.m_blockData
    }

    /**
        Get the size of the block attached to this message.
        @returns The size of the block (bytes). 0 if no block is attached.
     */

    pub fn GetBlockSize( &self ) -> i32
    {
        self.m_blockSize
    }

    /**
        Templated serialize function for the block message. Doesn't do anything. The block data is serialized elsewhere.
        You can override the serialize methods on a block message to implement your own serialize function. It's just like a regular message with a block attached to it.
        @see ConnectionPacket
        @see ChannelPacketData
        @see ReliableOrderedChannel
        @see UnreliableUnorderedChannel
     */

    pub fn Serialize<S: Stream>( &mut self, stream: &mut S ) -> bool { let _ = stream; true }
}

impl Serializable for BlockMessage
{
    YOJIMBO_VIRTUAL_SERIALIZE_FUNCTIONS!();
}

impl Message for BlockMessage
{
    fn base( &self ) -> &MessageBase { &self.base }
    fn base_mut( &mut self ) -> &mut MessageBase { &mut self.base }
    fn AsBlockMessage( &mut self ) -> Option<&mut BlockMessage> { Some( self ) }
}

// port: explicit BlockMessage(), the default constructor
impl Default for BlockMessage
{
    fn default() -> BlockMessage
    {
        BlockMessage::new()
    }
}

impl Drop for BlockMessage
{
    /**
        If a block was attached to the message, it is freed here.
     */

    fn drop( &mut self )
    {
        if !self.m_allocator.is_null()
        {
            YOJIMBO_FREE!( self.m_allocator, self.m_blockData );
            self.m_blockSize = 0;
            self.m_allocator = null_allocator();
        }
    }
}

/**
    Message factory error level.
 */

pub type MessageFactoryErrorLevel = i32;

pub const MESSAGE_FACTORY_ERROR_NONE: MessageFactoryErrorLevel = 0;                             // No error. All is well.
pub const MESSAGE_FACTORY_ERROR_FAILED_TO_ALLOCATE_MESSAGE: MessageFactoryErrorLevel = 1;       // Failed to allocate a message. Typically this means we ran out of memory on the allocator backing the message factory.

/**
    Defines the set of message types that can be created.

    You can derive a message factory yourself to create your own message types, or you can use these helper macros to do it for you:

        YOJIMBO_MESSAGE_FACTORY_START
        YOJIMBO_DECLARE_MESSAGE_TYPE
        YOJIMBO_MESSAGE_FACTORY_FINISH

    See shared.h for an example showing how to use the macros.
 */

/**
    Opaque debug-only message leak tracking state for a MessageFactory.
    Defined and used entirely inside libyojimbo (yojimbo_message.cpp), for the same reason as
    AllocatorDebugState: the pointer is present in every build, so MessageFactory has one
    layout whatever NDEBUG a consumer compiles with.
 */

// port: the class and the four functions are defined below, with the rest of yojimbo_message.cpp

// port: the class's data members live in MessageFactoryBase, which every factory struct embeds as `base`; the virtual
// methods are the MessageFactory trait (README, "Classes with virtual methods"). Factories are usually defined with
// YOJIMBO_MESSAGE_FACTORY! (below).

pub struct MessageFactoryBase
{
    m_debug: *mut MessageFactoryDebugState,                                 // Message leak tracking state, or NULL. Present in every configuration so the class has one layout; only allocated in a debug library build.
    m_allocator: *mut dyn Allocator,                                        // The allocator used to create messages.
    m_numTypes: i32,                                                        // The number of message types.
    m_errorLevel: MessageFactoryErrorLevel,                                 // The message factory error level.
}

impl MessageFactoryBase
{
    /**
        Message factory allocator.
        Pass in the number of message types for the message factory from the derived class.
        @param allocator The allocator used to create messages.
        @param numTypes The number of message types. Valid types are in [0,numTypes-1].
     */

    pub fn new( allocator: *mut dyn Allocator, numTypes: i32 ) -> MessageFactoryBase
    {
        MessageFactoryBase
        {
            m_allocator: allocator,
            m_numTypes: numTypes,
            m_errorLevel: MESSAGE_FACTORY_ERROR_NONE,
            m_debug: yojimbo_message_factory_debug_create(),
        }
    }
}

impl Drop for MessageFactoryBase
{
    /**
        Message factory destructor.
        Checks for message leaks when libyojimbo itself was built with YOJIMBO_DEBUG_MESSAGE_LEAKS non-zero. This is on by default in debug build.
     */

    fn drop( &mut self )
    {
        yojimbo_assert!( !self.m_allocator.is_null() );
        self.m_allocator = null_allocator();
        // Reports and fails on any leaked message, then frees the tracking state. Fails
        // through the assert handler rather than exit(1), so programs embedding yojimbo
        // (editors, tools) can intercept via yojimbo_set_assert_function.
        yojimbo_message_factory_debug_destroy( self.m_debug );
        self.m_debug = std::ptr::null_mut();
    }
}

pub trait MessageFactory
{
    // port: accessors for the embedded data members (README, "Classes with virtual methods")

    fn base( &self ) -> &MessageFactoryBase;

    fn base_mut( &mut self ) -> &mut MessageFactoryBase;

    /**
        Create a message by type.
        IMPORTANT: Check the message pointer returned by this call. It can be NULL if there is no memory to create a message!
        Messages returned from this function have one reference added to them. When you are finished with the message, pass it to MessageFactory::Release.
        @param type The message type in [0,numTypes-1].
        @returns The allocated message, or NULL if the message could not be allocated. If the message allocation fails, the message factory error level is set to MESSAGE_FACTORY_ERROR_FAILED_TO_ALLOCATE_MESSAGE.
        @see MessageFactory::AddRef
        @see MessageFactory::ReleaseMessage
     */

    fn CreateMessage( &mut self, r#type: i32 ) -> *mut dyn Message
    {
        yojimbo_assert!( r#type >= 0 );
        yojimbo_assert!( r#type < self.base().m_numTypes );

        let message = self.CreateMessageInternal( r#type );
        if message.is_null()
        {
            self.base_mut().m_errorLevel = MESSAGE_FACTORY_ERROR_FAILED_TO_ALLOCATE_MESSAGE;
            return null_message();
        }

        yojimbo_message_factory_debug_track_create( self.base().m_debug, message );

        message
    }

    /**
        Add a reference to a message.
        @param message The message to add a reference to.
        @see MessageFactory::Create
        @see MessageFactory::Release
     */

    fn AcquireMessage( &mut self, message: *mut dyn Message )
    {
        yojimbo_assert!( !message.is_null() );
        if !message.is_null()
        {
            unsafe { ( *message ).Acquire(); }
        }
    }

    /**
        Remove a reference from a message.
        Messages have 1 reference when created. When the reference count reaches 0, they are destroyed.
        @see MessageFactory::Create
        @see MessageFactory::AddRef
     */

    fn ReleaseMessage( &mut self, message: *mut dyn Message )
    {
        let mut message = message;
        yojimbo_assert!( !message.is_null() );
        if message.is_null()
        {
            return;
        }
        unsafe { ( *message ).Release(); }
        if unsafe { ( *message ).GetRefCount() } == 0
        {
            yojimbo_message_factory_debug_track_release( self.base().m_debug, message );
            yojimbo_assert!( !self.base().m_allocator.is_null() );
            let allocator = self.base().m_allocator;
            YOJIMBO_DELETE!( allocator, dyn Message, message );
        }
    }

    /**
        Get the number of message types supported by this message factory.
        @returns The number of message types.
     */

    fn GetNumTypes( &self ) -> i32
    {
        self.base().m_numTypes
    }

    /**
        Get the allocator used to create messages.
        @returns The allocator.
     */

    fn GetAllocator( &self ) -> *mut dyn Allocator
    {
        yojimbo_assert!( !self.base().m_allocator.is_null() );
        self.base().m_allocator
    }

    /// port: `&messageFactory.GetAllocator()` as a stream allocator context (see AllocatorToContext)
    fn GetAllocatorContext( &mut self ) -> *mut c_void
    {
        AllocatorToContext( &mut self.base_mut().m_allocator )
    }

    /**
        Get the error level.
        When used with a client or server, an error level on a message factory other than MESSAGE_FACTORY_ERROR_NONE triggers a client disconnect.
     */

    fn GetErrorLevel( &self ) -> MessageFactoryErrorLevel
    {
        self.base().m_errorLevel
    }

    /**
        Clear the error level back to no error.
     */

    fn ClearErrorLevel( &mut self )
    {
        self.base_mut().m_errorLevel = MESSAGE_FACTORY_ERROR_NONE;
    }

    // port: CreateMessageInternal and SetMessageType are protected upstream; trait methods are public

    /**
        This method is overridden to create messages by type.
        @param type The type of message to be created.
        @returns The message created. Its reference count is 1.
     */

    fn CreateMessageInternal( &mut self, r#type: i32 ) -> *mut dyn Message { let _ = r#type; null_message() }

    /**
        Set the message type of a message.
        @param message The message object.
        @param type The message type to set.
     */

    fn SetMessageType( &self, message: *mut dyn Message, r#type: i32 ) { unsafe { ( *message ).SetType( r#type ); } }
}

