// port: a macro_rules! macro can't open a class in one macro and close it in another, so the three upstream macros
// are one invocation, in either of two spellings:
//
//     YOJIMBO_MESSAGE_FACTORY_START!( TestMessageFactory, NUM_TEST_MESSAGE_TYPES,
//         YOJIMBO_DECLARE_MESSAGE_TYPE( TEST_MESSAGE, TestMessage );
//         YOJIMBO_DECLARE_MESSAGE_TYPE( TEST_BLOCK_MESSAGE, TestBlockMessage );
//     YOJIMBO_MESSAGE_FACTORY_FINISH() );
//
//     YOJIMBO_MESSAGE_FACTORY!( TestMessageFactory, NUM_TEST_MESSAGE_TYPES, {
//         TEST_MESSAGE => TestMessage,
//         TEST_BLOCK_MESSAGE => TestBlockMessage,
//     } );
//
// Either defines `pub struct TestMessageFactory { pub base: MessageFactoryBase }` with
// `TestMessageFactory::new( allocator: *mut dyn Allocator )` and a MessageFactory impl whose CreateMessageInternal
// does YOJIMBO_NEW!( allocator, message_class, Default::default() ) and SetMessageType, as upstream. Message types are
// integer expressions (usually `pub const X: i32`).
#[macro_export]
macro_rules! YOJIMBO_MESSAGE_FACTORY_START {
    ( $factory_class:ident, $num_message_types:expr, $( YOJIMBO_DECLARE_MESSAGE_TYPE ( $message_type:expr, $message_class:ty ) ; )* YOJIMBO_MESSAGE_FACTORY_FINISH ( ) ) => {
        $crate::YOJIMBO_MESSAGE_FACTORY!( $factory_class, $num_message_types, { $( $message_type => $message_class ),* } );
    };
}

#[macro_export]
macro_rules! YOJIMBO_MESSAGE_FACTORY {
    ( $factory_class:ident, $num_message_types:expr, { $( $message_type:expr => $message_class:ty ),* $(,)? } ) => {
        pub struct $factory_class
        {
            pub base: $crate::MessageFactoryBase,
        }

        impl $factory_class
        {
            pub fn new( allocator: *mut dyn $crate::Allocator ) -> $factory_class
            {
                $factory_class { base: $crate::MessageFactoryBase::new( allocator, ( $num_message_types ) as i32 ) }
            }
        }

        impl $crate::MessageFactory for $factory_class
        {
            fn base( &self ) -> &$crate::MessageFactoryBase { &self.base }

            fn base_mut( &mut self ) -> &mut $crate::MessageFactoryBase { &mut self.base }

            fn CreateMessageInternal( &mut self, r#type: i32 ) -> *mut dyn $crate::Message
            {
                let mut message: *mut dyn $crate::Message;
                let allocator: *mut dyn $crate::Allocator = $crate::MessageFactory::GetAllocator( self );
                let _ = allocator;
                // port: the switch is an if chain, so message types can be any integer expression
                $(
                    if r#type == ( $message_type ) as i32
                    {
                        let p: *mut $message_class = $crate::YOJIMBO_NEW!( allocator, $message_class, <$message_class as ::core::default::Default>::default() );
                        if p.is_null()
                        {
                            return $crate::null_message();
                        }
                        message = p as *mut dyn $crate::Message;
                        $crate::MessageFactory::SetMessageType( self, message, ( $message_type ) as i32 );
                        return message;
                    }
                )*
                return $crate::null_message();
            }
        }
    };
}

/**
    Helper function to serialize a block attached to a message. Used by channel implementations.
 */

pub fn SerializeMessageBlock<S: Stream>( stream: &mut S, messageFactory: *mut dyn MessageFactory, blockMessage: *mut BlockMessage, maxBlockSize: i32 ) -> bool
{
    let blockMessage = unsafe { &mut *blockMessage };
    let mut blockSize: i32 = if S::IsWriting { blockMessage.GetBlockSize() } else { 0 };
    serialize_int!( stream, blockSize, 1, maxBlockSize );
    let blockData: *mut u8;
    if S::IsReading
    {
        let allocator: *mut dyn Allocator = unsafe { ( *messageFactory ).GetAllocator() };
        blockData = YOJIMBO_ALLOCATE!( allocator, blockSize as usize );
        if blockData.is_null()
        {
            yojimbo_printf!( YOJIMBO_LOG_LEVEL_ERROR, "error: failed to allocate message block (SerializeMessageBlock)\n" );
            return false;
        }
        blockMessage.AttachBlock( allocator, blockData, blockSize );
    }
    else
    {
        blockData = blockMessage.GetBlockData();
    }
    // port: the block pointer becomes a slice for serialize_bytes
    let blockSlice: &mut [u8] = unsafe { std::slice::from_raw_parts_mut( blockData, blockSize as usize ) };
    serialize_bytes!( stream, blockSlice, blockSize );
    true
}

