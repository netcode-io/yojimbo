// The message leak tracker lives here, behind MessageFactory::m_debug, instead of in the
// public header. MessageFactory is a base class consumers derive from (usually through
// YOJIMBO_MESSAGE_FACTORY_START), so a member whose presence depends on NDEBUG gave the class
// two layouts: one for a debug build of the library and another for a release consumer that
// included the same header. One pointer, always present, one layout.
pub struct MessageFactoryDebugState
{
    // port: YOJIMBO_DEBUG_MESSAGE_LEAKS is on in debug builds (cfg(debug_assertions)), as upstream. The map is keyed by
    // the message's address, as std::map<void*,int>, and holds the message itself for the leak report.
    #[cfg(debug_assertions)]
    allocated_messages: BTreeMap<*mut u8, *mut dyn Message>,
}

pub fn yojimbo_message_factory_debug_create() -> *mut MessageFactoryDebugState
{
    #[cfg(debug_assertions)]
    {
        // The tracker's own std::map allocates from the global heap, and always did; the state
        // object joins it there rather than routing through the factory's allocator.
        return Box::into_raw( Box::new( MessageFactoryDebugState { allocated_messages: BTreeMap::new() } ) );
    }
    #[cfg(not(debug_assertions))]
    {
        return std::ptr::null_mut();
    }
}

pub fn yojimbo_message_factory_debug_destroy( debug: *mut MessageFactoryDebugState )
{
    #[cfg(debug_assertions)]
    {
        yojimbo_assert!( !debug.is_null() );
        let state = unsafe { &mut *debug };
        if state.allocated_messages.len() != 0
        {
            yojimbo_printf!( YOJIMBO_LOG_LEVEL_ERROR, "you leaked messages!\n" );
            yojimbo_printf!( YOJIMBO_LOG_LEVEL_ERROR, "{} messages leaked\n", state.allocated_messages.len() as i32 );
            for ( _, i ) in state.allocated_messages.iter()
            {
                let message: *mut dyn Message = *i;
                unsafe
                {
                    yojimbo_printf!( YOJIMBO_LOG_LEVEL_ERROR, "leaked message {:p} (type {}, refcount {})\n", message as *mut u8, ( *message ).GetType(), ( *message ).GetRefCount() );
                }
            }
            yojimbo_assert!( false && "Message leaks detected, see log".is_empty() );
        }
    }
    // delete debug
    if !debug.is_null()
    {
        drop( unsafe { Box::from_raw( debug ) } );
    }
}

pub fn yojimbo_message_factory_debug_track_create( debug: *mut MessageFactoryDebugState, message: *mut dyn Message )
{
    let _ = debug;
    let _ = message;
    #[cfg(debug_assertions)]
    {
        yojimbo_assert!( !debug.is_null() );
        unsafe { ( *debug ).allocated_messages.insert( message as *mut u8, message ); }
    }
}

pub fn yojimbo_message_factory_debug_track_release( debug: *mut MessageFactoryDebugState, message: *mut dyn Message )
{
    let _ = debug;
    let _ = message;
    #[cfg(debug_assertions)]
    {
        yojimbo_assert!( !debug.is_null() );
        let state = unsafe { &mut *debug };
        yojimbo_assert!( state.allocated_messages.contains_key( &( message as *mut u8 ) ) );
        state.allocated_messages.remove( &( message as *mut u8 ) );
    }
}
